// Числа словами → цифри: «двадцять третій» → 23, «сто дев'ятнадцятий» → 119,
// «шістнадцятого» → 16, «перше» → 1. Працює з уже нормалізованими словами (без апострофів).

const ORD_END = '(ий|ій|а|я|е|є|ого|ього|ому|ьому|ім|им|у|ю|ої|ьої|их|іх|ими)';
const CARD_END = '(ь|и|ьох|ьом|ма|ох|ом)';

// [основа, значення, чи може бути кількісним теж (з закінченнями CARD_END)]
const STEMS = [
  ['одинадцят', 11, 1], ['дванадцят', 12, 1], ['тринадцят', 13, 1], ['чотирнадцят', 14, 1],
  ['пятнадцят', 15, 1], ['шістнадцят', 16, 1], ['сімнадцят', 17, 1], ['вісімнадцят', 18, 1],
  ['девятнадцят', 19, 1], ['двадцят', 20, 1], ['тридцят', 30, 1], ['сороков', 40, 0],
  ['пятдесят', 50, 1], ['шістдесят', 60, 1], ['сімдесят', 70, 1], ['вісімдесят', 80, 1],
  ['девяност', 90, 0], ['десят', 10, 1], ['сот', 100, 0],
  ['перш', 1, 0], ['друг', 2, 0], ['трет', 3, 0], ['четверт', 4, 0], ['пят', 5, 0],
  ['шост', 6, 0], ['сьом', 7, 0], ['восьм', 8, 0], ['девят', 9, 0],
];
const EXACT = {
  один: 1, одна: 1, одне: 1, одного: 1, одну: 1, два: 2, дві: 2, двох: 2, три: 3, трьох: 3,
  чотири: 4, чотирьох: 4, пять: 5, пяти: 5, шість: 6, шести: 6, сім: 7, семи: 7,
  вісім: 8, восьми: 8, девять: 9, девяти: 9, десять: 10, десяти: 10,
  сорок: 40, сорока: 40, девяносто: 90, сто: 100, ста: 100, двісті: 200, двохсот: 200,
  // кілька російських форм — проповідники іноді переходять на них
  первое: 1, первого: 1, второе: 2, второго: 2, третье: 3, третьего: 3,
};

const STEM_RE = STEMS.map(([stem, value, card]) => ({
  re: new RegExp('^' + stem + (card ? `(${ORD_END.slice(1, -1)}|${CARD_END.slice(1, -1)})` : ORD_END) + '$'),
  value,
}));

/** Значення одного слова-числа або null. */
export function wordValue(word) {
  if (/^\d+$/.test(word)) return Number(word);
  if (word in EXACT) return EXACT[word];
  for (const s of STEM_RE) if (s.re.test(word)) return s.value;
  return null;
}

/** Склеює сусідні слова-числа: [«двадцять», «третій»] → 23. Повертає масив токенів
 *  { word, num?, from, to } (from/to — індекси вихідних слів). */
export function foldNumbers(words) {
  const out = [];
  for (let i = 0; i < words.length; i++) {
    const v = wordValue(words[i]);
    if (v === null) { out.push({ word: words[i], from: i, to: i }); continue; }
    const isDigits = /^\d+$/.test(words[i]);
    let total = v, j = i;
    if (!isDigits) {
      // сотні + десятки + одиниці: «сто двадцять третій»
      while (j + 1 < words.length && !/^\d+$/.test(words[j + 1])) {
        const n = wordValue(words[j + 1]);
        if (n === null) break;
        const lastPlace = total % 100 === 0 ? 100 : total % 10 === 0 && total >= 20 ? 10 : 1;
        if ((lastPlace === 100 && n < 100) || (lastPlace === 10 && n < 10)) { total += n; j++; }
        else break;
      }
    }
    out.push({ word: String(total), num: total, from: i, to: j });
    i = j;
  }
  return out;
}
